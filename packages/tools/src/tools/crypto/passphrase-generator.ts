function secureRandomInt(max: number): number {
  const array = new Uint32Array(1);
  // Rejection sampling to eliminate modulo bias
  const limit = Math.floor(0x100000000 / max) * max;
  do {
    crypto.getRandomValues(array);
  } while (array[0]! >= limit);
  return array[0]! % max;
}

export const passphraseGenerator = defineTool({
  meta: {
    id: "crypto/passphrase-generator",
    name: "Passphrase Generator",
    description:
      "Free online passphrase generator — generate diceware-style passphrases instantly in your browser. No data is stored. Configurable word count, separator, capitalization, and optional number suffix from an 800+ word list.",
    category: "crypto",
    subgroup: "Password Tools",
    tier: ToolTier.CLIENT,
    keywords: [
      "passphrase",
      "diceware",
      "generate",
      "random",
      "words",
      "crypto",
    ],
    icon: "KeyRound",
    examples: [
      {
        title: "6-Word Passphrase",
        description: "Generate a diceware-style passphrase with 6 random words",
        input: {
          wordCount: 6,
          separator: "-",
          capitalize: false,
          includeNumber: false,
          count: 1,
        },
        output:
          "(Diceware passphrase, e.g., apple-forest-beacon-crystal-harbor-flame — output varies due to random word selection)",
      },
    ],
  },
  inputSchema,
  outputSchema,
  execute: (input) => {
    const passphrases: string[] = [];

    for (let n = 0; n < input.count; n++) {
      const words: string[] = [];
      for (let i = 0; i < input.wordCount; i++) {
        let word = WORD_LIST[secureRandomInt(WORD_LIST.length)]!;
        if (input.capitalize) {
          word = word.charAt(0).toUpperCase() + word.slice(1);
        }
        words.push(word);
      }

      let passphrase = words.join(input.separator);
      if (input.includeNumber) {
        passphrase += input.separator + secureRandomInt(1000).toString();
      }
      passphrases.push(passphrase);
    }

    return { output: passphrases.join("\n") };
  },
});
